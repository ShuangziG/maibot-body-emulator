def install() -> int:
    """把扩展数据合并进 food 模块（就地修改），返回新增食物条数。"""
    from . import food as _f

    added = 0
    for row in _ROWS:
        key, label, group, portion, vol, water, na, carb, prot, fat, alc, caf, gi, _aliases = row
        if key in _f.FOODS:
            continue
        kcal = round(4 * carb + 4 * prot + 9 * fat + 7 * alc)
        _f.FOODS[key] = Food(key, label, group, portion, vol, water, na,
                             carb, prot, fat, alc, caf, kcal, gi)
        added += 1

    # 别名：长词优先，且本表覆盖旧表（原来「奶茶」映射到 Milk，这里改指 MilkTea）
    pairs = []
    for row in _ROWS:
        key, label, aliases = row[0], row[1], row[13]
        pairs.append((label, [key]))
        for alias in aliases:
            pairs.append((alias, [key]))
    pairs.extend(_ALIAS_EXTRA)
    pairs.sort(key=lambda item: -len(item[0]))

    merged, seen = [], set()
    for word, keys in pairs:
        if word in seen or not all(k in _f.FOODS for k in keys):
            continue
        seen.add(word)
        merged.append((word, keys))
    # 注意：不能简单接在旧表后面 —— parse_menu 是按列表顺序做「长词优先」的，
    # 旧表整段追加会让「油条」(2 字) 抢在「生榨米粉」(4 字) 前面，把
    # 「生榨米粉配油条」解析成 油条+Rice 而不是 Rice+油条。
    # 所以新旧合并后再整体按词长倒序排一次；sorted 是稳定的，
    # 同长度时仍是「本表优先、旧表保持原序」。
    all_pairs = merged + [(w, k) for w, k in _f.FOOD_ALIASES if w not in seen]
    _f.FOOD_ALIASES[:] = sorted(all_pairs, key=lambda item: -len(item[0]))

    # 拆解用 key 清单
    have = {k for k, _ in _f._DECOMPOSE_KEYS}
    for key, label in _DECOMPOSE_EXTRA:
        if key in _f.FOODS and key not in have:
            _f._DECOMPOSE_KEYS.append((key, label))
            have.add(key)

    # 三餐 / 饮品 / 加餐池：原地 append，引用方能看到
    for slot, combos in _MEAL_EXTRA.items():
        pool = _f.MEAL_POOLS.get(slot)
        if isinstance(pool, list):
            for combo in combos:
                combo = [k for k in combo if k in _f.FOODS]
                if combo and combo not in pool:
                    pool.append(combo)
    for key in _DRINK_EXTRA:
        if key in _f.FOODS and key not in _f.DRINK_POOL:
            _f.DRINK_POOL.append(key)
    for key in _SNACK_EXTRA:
        if key in _f.FOODS and key not in _f.SNACK_POOL:
            _f.SNACK_POOL.append(key)

    # is_plain_food 的「要不要送模型拆」清单收窄。
    # 原因：plugin.py 里 len(resolved)==1 且 not is_plain_food(...) 就会调
    # utils 模型再拆一次。旧表把「奶茶」列为需要拆的复合菜名，可是本表已经
    # 有了精确食物 MilkTea —— 再拆一次反而可能被模型拆回 Milk + Water，
    # issue 要修的「糖分丢失」就绕回来了。
    # 规则：别名唯一映射到某个食物、且该食物的中文名与词完全相同的，视为
    # 普通食物，不再拆；其余（映射多 key，或名字对不上）继续交给模型。
    first_hit: dict = {}
    for word, keys in _f.FOOD_ALIASES:
        if word not in first_hit:
            first_hit[word] = keys
    keep = set()
    for word in _f._DISH_WORDS:
        keys = first_hit.get(word)
        exact = (keys and len(keys) == 1 and keys[0] in _f.FOODS
                 and _f.FOODS[keys[0]].label == word)
        if not exact:
            keep.add(word)
    _f._DISH_WORDS = frozenset(keep)

    _f.ALL_FOODS[:] = list(_f.FOODS.values())
    _f.SELECTABLE[:] = [f for f in _f.ALL_FOODS if f.selectable]
    return added
